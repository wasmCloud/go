// Package plugin is the wasmCloud Go SDK for authoring host component
// plugins: WebAssembly components that EXPORT capability interfaces and are
// run by the wasmCloud host in a long-lived, supervised store, serving
// concurrent capability calls from every workload that imports the
// interfaces they export.
//
// A plugin defines its own WIT world that exports its capability interface
// and may use the wasmcloud:host@0.1.3 interfaces (vendored under wit/):
//
//   - [go.wasmcloud.dev/plugin/hostidentity] wraps the
//     wasmcloud:host/identity import: the calling workload/component id.
//   - [go.wasmcloud.dev/plugin/hostcancel] wraps the wasmcloud:host/cancel
//     import: cooperative cancellation of the plugin's own invocations.
//   - [go.wasmcloud.dev/plugin/lifecycle] wires the optional
//     wasmcloud:host/workload-lifecycle EXPORT: bind/unbind hooks the host
//     invokes as workloads come and go.
//
// Plugins are built with componentize-go; the async world is recommended,
// since the host serves concurrent calls through one plugin store. See
// README.md for a full walkthrough, including the wash `dev.host_plugins`
// config key that loads a plugin into the dev host.
//
// Generated bindings under imports/ and exports/ are regenerated by
// regenerate_bindings.sh — do not edit them.
