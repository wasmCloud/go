// Package component is the wasmCloud Go SDK for building WebAssembly
// components.
//
// The SDK targets two worlds defined in wit/world.wit:
//
//   - wasip2 (default): a sync WASI P2 component exporting
//     wasi:http/incoming-handler@0.2.8, buildable with stock Go via
//     componentize-go.
//   - wasip3 (opt-in): an async WASI P3 component exporting
//     wasi:http/handler@0.3.0 with streaming bodies and native
//     concurrency.
//
// HTTP, logging, and config helpers live in
// [go.bytecodealliance.org/pkg/wasihttp],
// [go.bytecodealliance.org/pkg/wasilog], and
// [go.bytecodealliance.org/pkg/wasiconfig]; the packages under this module
// are deprecated forwarding shims kept for compatibility.
//
// Components are built with `go tool componentize-go build`; the default
// world is declared in componentize-go.toml. Export glue under exports/ is
// generated by regenerate_bindings.sh — do not edit it.
